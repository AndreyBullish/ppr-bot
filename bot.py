async def cmd_works(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """
    /works ТО1 OV2
    /works ТО3 отопление
    """
    if not context.args or len(context.args) < 2:
        await update.message.reply_text(
            "❌ Укажите номер ТО и систему.\n\n"
            "Примеры:\n"
            "/works ТО1 OV2\n"
            "/works ТО3 отопление\n"
            "/works ТО4 пароснабжение\n\n"
            "Список систем: /systems",
            parse_mode="Markdown"
        )
        return

    raw = context.args[0].strip().replace("-", "").upper()
    # Заменяем латинские T/O на кириллические (другая раскладка клавиатуры)
    raw = raw.replace("T", "Т").replace("O", "О")
    # Нормализуем: ТО1 / ТО-1 / то1 / 1 -> ТО1
    if raw in ("1", "2", "3", "4"):
        to_arg = f"ТО{raw}"
    else:
        to_arg = raw

    system_query = " ".join(context.args[1:])
    system_name = find_system(system_query)

    if not system_name:
        await update.message.reply_text(
            f"❌ Система *{system_query}* не найдена.\n\n"
            "Используйте /systems для просмотра списка систем.",
            parse_mode="Markdown"
        )
        return

    system_data = WORKS_DATA.get(system_name, {})
    works = system_data.get(to_arg)

    if works is None:
        available = ", ".join(system_data.keys())
        await update.message.reply_text(
            f"❌ Для системы *{system_name}* нет данных по *{to_arg}*.\n\n"
            f"Доступные виды ТО: {available}",
            parse_mode="Markdown"
        )
        return

    lines = [f"🔧 *{to_arg} — {system_name}*\n"]
    for i, work in enumerate(works, 1):
        # Переводим в Title Case для читаемости
        work_fmt = work.capitalize()
        lines.append(f"{i}. {work_fmt}")

    await update.message.reply_text("\n".join(lines), parse_mode="Markdown")


