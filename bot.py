def build_message(month_name: str) -> str:
    data = SCHEDULE.get(month_name)
    if not data:
        return None
    lines = [f"🔔 *Напоминание о плановом ТО — {month_name.capitalize()}*\n"]
    lines.append("В этом месяце необходимо выполнить:\n")
    to3 = data.get("ТО-3", [])
    to4 = data.get("ТО-4", [])
    if to3:
        lines.append("📋 *ТО-3* (полугодовое):")
        for s in to3:
            lines.append(f"  • {s}")
        lines.append("")
    if to4:
        lines.append("📋 *ТО-4* (годовое):")
        for s in to4:
            lines.append(f"  • {s}")
        lines.append("")
    lines.append("✅ Просьба подтвердить назначение ответственных и сроки выполнения.")
    return "\n".join(lines)


def find_system(query: str):
    """Найти систему по запросу (частичное совпадение)."""
    q = query.strip().lower()

    # Точное совпадение с псевдонимом
    if q in SYSTEM_ALIASES:
        return SYSTEM_ALIASES[q]

    # Точное совпадение с ключом WORKS_DATA
    for key in WORKS_DATA:
        if q == key.lower():
            return key

    # Частичное совпадение с псевдонимом
    for alias, system in SYSTEM_ALIASES.items():
        if q in alias or alias in q:
            return system

    # Частичное совпадение с ключом WORKS_DATA
    for key in WORKS_DATA:
        if q in key.lower():
            return key

    return None


